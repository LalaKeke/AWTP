RUN_DIR="${PNN_SAVE_DIR:-${HIPAD_ROOT}/outputs/pnn_closedloop_priority_stage1}"
LOG_DIR="${PNN_LOG_DIR:-${HIPAD_ROOT}/outputs/logs/closedloop_priority_stage1}"

for path in "${OLD_DATA}" "${NEW_DATA}" "${SUPERVISION}" "${PARENT}"; do
    [[ -s "${path}" ]] || { echo "ERROR: missing ${path}" >&2; exit 1; }
    [[ "${path}" != *"/evaluation/"* ]] || {
        echo "ERROR: evaluation result cannot be training input: ${path}" >&2
        exit 2
    }
done
if [[ -s "${RUN_DIR}/checkpoints/last.pth" && "${PNN_ALLOW_RESUME:-0}" != "1" ]]; then
    echo "ERROR: ${RUN_DIR}/checkpoints/last.pth exists; set PNN_ALLOW_RESUME=1 to resume" >&2
    exit 3
fi

mkdir -p "${RUN_DIR}/checkpoints" "${LOG_DIR}"
sha256sum "${OLD_DATA}" "${NEW_DATA}" "${SUPERVISION}" "${PARENT}" \
    > "${RUN_DIR}/training_inputs.sha256"

echo "[closedloop-priority] parent=${PARENT}"
echo "[closedloop-priority] run=${RUN_DIR}"
echo "[closedloop-priority] sparse targets are route intent; actor/lane safety gates route tracking"
echo "[closedloop-priority] checkpoint selection uses closed-loop DS/SR, not open-loop L2"

